"""Configuration and key management.

Keys are read from environment variables, optionally seeded from a local
``.env`` file. The real file is ignored by git; ``.env.example`` only contains
placeholders. Keys are never logged and never written to the database.
"""

from __future__ import annotations

import base64
import binascii
import os
import secrets
from dataclasses import dataclass
from pathlib import Path

from .errors import ConfigError

DEFAULT_DB_PATH = "ledger.sqlite"
DEFAULT_SCHEMAS_DIR = Path("assignment-a-data") / "schemas"
DEFAULT_ENV_FILE = Path(".env")

ENV_ENC_KEY = "AU_PII_ENC_KEY"
ENV_HMAC_KEY = "AU_PII_HMAC_KEY"
KEY_BYTES = 32


@dataclass(frozen=True)
class KeyConfig:
    """Validated 32-byte AES and HMAC keys."""

    enc_key: bytes
    hmac_key: bytes

    def __post_init__(self) -> None:
        if len(self.enc_key) != KEY_BYTES:
            raise ConfigError(f"{ENV_ENC_KEY} must decode to exactly {KEY_BYTES} bytes")
        if len(self.hmac_key) != KEY_BYTES:
            raise ConfigError(f"{ENV_HMAC_KEY} must decode to exactly {KEY_BYTES} bytes")
        if self.enc_key == self.hmac_key:
            raise ConfigError("encryption and HMAC keys must be different")

    @classmethod
    def from_env(cls, env_file: str | Path | None = None) -> "KeyConfig":
        """Load keys from the process environment.

        If ``env_file`` is supplied, missing variables are filled from it first.
        Existing process environment variables always win.
        """
        if env_file is not None:
            load_env_file(env_file)
        enc_raw = os.environ.get(ENV_ENC_KEY)
        hmac_raw = os.environ.get(ENV_HMAC_KEY)
        if not enc_raw or not hmac_raw:
            raise ConfigError(
                f"missing {ENV_ENC_KEY} and/or {ENV_HMAC_KEY}; "
                "run `au-ledger init-keys` or set the environment variables"
            )
        return cls(
            enc_key=_decode_key(enc_raw, ENV_ENC_KEY),
            hmac_key=_decode_key(hmac_raw, ENV_HMAC_KEY),
        )


def _decode_key(value: str, label: str) -> bytes:
    cleaned = value.strip()
    if len(cleaned) >= 2 and cleaned[0] == cleaned[-1] and cleaned[0] in {"'", '"'}:
        cleaned = cleaned[1:-1]
    try:
        decoded = base64.b64decode(cleaned, validate=True)
    except (binascii.Error, ValueError) as exc:
        raise ConfigError(f"{label} is not valid base64") from exc
    if len(decoded) != KEY_BYTES:
        raise ConfigError(f"{label} must decode to exactly {KEY_BYTES} bytes")
    return decoded


def generate_keypair() -> tuple[str, str]:
    """Return independent base64-encoded 32-byte keys."""
    return (
        base64.b64encode(secrets.token_bytes(KEY_BYTES)).decode("ascii"),
        base64.b64encode(secrets.token_bytes(KEY_BYTES)).decode("ascii"),
    )


def write_env_file(
    path: str | Path,
    enc_key_b64: str,
    hmac_key_b64: str,
    *,
    force: bool = False,
) -> Path:
    """Persist keys to a local file with owner-only permissions where possible."""
    target = Path(path)
    target.parent.mkdir(parents=True, exist_ok=True)
    flags = os.O_WRONLY | os.O_CREAT | (os.O_TRUNC if force else os.O_EXCL)
    try:
        fd = os.open(str(target), flags, 0o600)
    except FileExistsError as exc:
        raise ConfigError(
            f"refusing to overwrite existing key file: {target} (use --force to replace)"
        ) from exc
    try:
        content = (
            "# Auto-generated by au-ledger init-keys. Do not commit this file.\n"
            f"{ENV_ENC_KEY}={enc_key_b64}\n"
            f"{ENV_HMAC_KEY}={hmac_key_b64}\n"
        )
        with os.fdopen(fd, "w", encoding="utf-8", newline="\n") as handle:
            handle.write(content)
    except BaseException:
        try:
            os.close(fd)
        except OSError:
            pass
        raise
    try:
        os.chmod(target, 0o600)
    except OSError:
        # Windows may not honour POSIX modes; the file is still outside git.
        pass
    return target


def load_env_file(path: str | Path) -> None:
    """Minimal .env loader.

    Existing process environment variables take precedence. Values may be
    single- or double-quoted. Comments and blank lines are ignored.
    """
    target = Path(path)
    if not target.exists():
        raise ConfigError(f"environment file not found: {target}")
    for line_number, line in enumerate(target.read_text(encoding="utf-8").splitlines(), 1):
        stripped = line.strip()
        if not stripped or stripped.startswith("#"):
            continue
        if stripped.startswith("export "):
            stripped = stripped[len("export ") :].lstrip()
        if "=" not in stripped:
            raise ConfigError(f"invalid environment line {line_number} in {target.name}")
        key, value = stripped.split("=", 1)
        key = key.strip()
        value = value.strip()
        if len(value) >= 2 and value[0] == value[-1] and value[0] in {"'", '"'}:
            value = value[1:-1]
        if not key:
            raise ConfigError(f"empty environment key on line {line_number} in {target.name}")
        os.environ.setdefault(key, value)
